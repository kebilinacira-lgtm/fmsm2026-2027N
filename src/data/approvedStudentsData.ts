// Quick index set of all official matricules for O(1) lookups
const MATRICULE_INDEX = new Map<string, ApprovedStudent>();

APPROVED_STUDENTS_LIST.forEach(st => {
  const normEtud = st.matriculeEtudiant.trim().toLowerCase();
  const normBac = st.matriculeBac.trim().toLowerCase();
  MATRICULE_INDEX.set(normEtud, st);
  MATRICULE_INDEX.set(normBac, st);
  if (st.nin) {
    MATRICULE_INDEX.set(st.nin.trim().toLowerCase(), st);
  }
});

/**
 * Verifies if an entered matricule or identifier belongs to an officially registered student.
 */
export function verifyStudentMatricule(identifier: string): {
  isVerified: boolean;
  student?: ApprovedStudent;
  message: string;
} {
  if (!identifier) {
    return {
      isVerified: false,
      message: 'يرجى إدخال رقم التسجيل الجامعي أو رقم البكالوريا للتحقق.'
    };
  }

  const clean = identifier.trim().toLowerCase();
  
  // 1. Direct lookup
  let found = MATRICULE_INDEX.get(clean);

  // 2. Partial lookup if student enters with or without prefixes
  if (!found) {
    found = APPROVED_STUDENTS_LIST.find(st => 
      st.matriculeEtudiant.toLowerCase() === clean ||
      st.matriculeBac.toLowerCase() === clean ||
      (st.nin && st.nin.toLowerCase() === clean) ||
      clean.includes(st.matriculeBac.toLowerCase()) ||
      st.matriculeEtudiant.toLowerCase().includes(clean)
    );
  }

  if (found) {
    return {
      isVerified: true,
      student: found,
      message: `تم التحقق بنجاح: الطالب(ة) ${found.nomAr} ${found.prenomAr} مقيد رسمياً في ${found.departmentNameAr} (${found.level}).`
    };
  }

  return {
    isVerified: false,
    message: 'تنبيه أمني: رقم التسجيل غير موجود في السجل الرسمي لطلبة كلية الرياضيات وعلوم المادة لهذا العام الجامعي. أنت مسجل كـ "زائر / غير معتمد" ولن يُسمح لك بالدخول إلى فضاء الطلبة الرسمي.'
  };
}

/**
 * Returns a slice of sample verified matricules for testing and demonstration in the portal.
 */
export function getSampleVerifiedMatricules(): { matricule: string; name: string; dept: string; level: string }[] {
  return APPROVED_STUDENTS_LIST.slice(0, 8).map(st => ({
    matricule: st.matriculeEtudiant,
    name: `${st.nomAr} ${st.prenomAr}`,
    dept: st.departmentNameAr,
    level: st.level
  }));
}
